#!/usr/bin/env python3
"""Write assets/glossary/CLIPS_TABLE.md: every exercise of every program, with
its clip status and which tool/model made it, so clips can be remade later with
one consistent model (or replaced by Felipe's own filmed clips).

Run from the repo root: python3 scripts/clips/clips-table.py
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
G = os.path.join(ROOT, "assets", "glossary")


def live_slugs(program):
    """Exercise slugs that have a clip line in the site's clip maps."""
    if program == "hips":
        text = open(os.path.join(ROOT, "content/programs/hips-clips.ts")).read()
        return set(re.findall(r'"([a-z0-9-]+)":\s*"/programs/hips/clips/', text))
    text = open(os.path.join(ROOT, "content/programs/program-clips.ts")).read()
    return set(re.findall(rf'"([a-z0-9-]+)":\s*"/programs/{program}/clips/', text))


order = json.load(open(os.path.join(G, "queues.json")))["order"]
out = [
    "# Demo clips: status and model",
    "",
    "Generated by `scripts/clips/clips-table.py` from the queue files. Do not edit by hand.",
    "",
    "Mission 1: every exercise has a clip. Mission 2: remake them all with one model",
    "(or Felipe's own filmed clips), using the Source column to find the odd ones out.",
    "",
]
totals = {"live": 0, "all": 0}
for prog in order:
    path = os.path.join(G, f"{prog}-queue.json")
    if not os.path.exists(path):
        continue
    q = json.load(open(path))
    live = live_slugs(prog)
    clips = q["clips"]
    n_live = sum(1 for c in clips if c["slug"] in live)
    totals["live"] += n_live
    totals["all"] += len(clips)
    out += [f"## {prog} ({n_live}/{len(clips)} live)", "",
            "| # | Exercise | Status | On site | Tries | Source / model |",
            "|---|---|---|---|---|---|"]
    for c in clips:
        check = "with Felipe" if "check with felipe" in (c.get("note") or "").lower() else ""
        status = c["status"] + (f" ({check})" if check else "")
        out.append(
            f"| {c['n']} | {c['name']} | {status} | {'yes' if c['slug'] in live else ''} | "
            f"{c.get('attempts', 0)} | {c.get('source') or ''} |"
        )
    out.append("")
out.insert(4, f"**{totals['live']} of {totals['all']} clips live.**\n")
open(os.path.join(G, "CLIPS_TABLE.md"), "w").write("\n".join(out) + "\n")
print(f"wrote assets/glossary/CLIPS_TABLE.md ({totals['live']}/{totals['all']} live)")
